"""
Inference Pipeline for Landslide Susceptibility Prediction.

Project: AI-Based Smart Logistics & Accessibility Platform for North Eastern Region (NER)
Pilot Region: Sikkim, India
Module: Random Forest Landslide Susceptibility Model

This module provides both a programmatic API and a command-line interface (CLI)
for executing landslide susceptibility inference using the trained Random Forest
pipeline.

CRITICAL OPERATIONAL & SCIENTIFIC NOTICE:
- Predictions generated by this model represent TERRAIN-BASED LANDSLIDE SUSCEPTIBILITY SCORES
  (spatial likelihood of landslide initiation under baseline geological, topographic, and soil conditions).
- Susceptibility scores are strictly NOT calibrated road-disruption probabilities,
  road closure probabilities, traffic delay likelihoods, or real-time rainfall-induced hazard states.
- Do NOT use raw susceptibility scores as direct operational road closure thresholds.
"""

import argparse
import json
import logging
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple, Union

import joblib
import numpy as np
import pandas as pd

# Setup logging
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s"
)
logger = logging.getLogger("LandslideSusceptibilityInference")

# Default paths relative to this script
SCRIPT_DIR = Path(__file__).resolve().parent
DEFAULT_MODEL_PATH = SCRIPT_DIR / "models" / "random_forest_final_v2.joblib"
FALLBACK_BASELINE_MODEL_PATH = SCRIPT_DIR / "models" / "final_random_forest_pipeline.joblib"
SCHEMA_PATH = SCRIPT_DIR / "models" / "feature_schema_v2.json"

# Expected features
EXPECTED_NUMERICAL_FEATURES: List[str] = [
    "elevation",
    "slope",
    "aspect_sin",
    "aspect_cos",
    "is_flat_aspect",
    "curvature_total",
    "plan_curvature",
    "profile_curvature",
    "terrain_ruggedness_tri",
    "topographic_position_tpi",
    "clay_0_5cm",
    "clay_5_15cm",
    "clay_diff_5_15_minus_0_5",
    "sand_0_5cm",
    "sand_5_15cm",
    "sand_diff_5_15_minus_0_5",
    "soc_0_5cm",
    "soc_5_15cm",
    "soc_diff_5_15_minus_0_5",
    "phh2o_0_5cm",
    "phh2o_5_15cm",
    "ph_diff_5_15_minus_0_5",
    "distance_to_roads_m",
]

EXPECTED_CATEGORICAL_FEATURES: List[str] = [
    "landcover_code",
]

ALL_EXPECTED_FEATURES: List[str] = EXPECTED_NUMERICAL_FEATURES + EXPECTED_CATEGORICAL_FEATURES

# Recognized identifier columns to preserve
ID_COLUMNS: List[str] = [
    "record_id",
    "segment_id",
    "scenario_id",
    "inventory_id",
    "original_id",
    "osm_way_ids",
    "u",
    "v",
    "edge_key",
    "road_name",
    "road_type",
    "id",
]

# Classification thresholds
LOW_THRESHOLD = 0.35
HIGH_THRESHOLD = 0.65

DISCLAIMER_TEXT = (
    "DISCLAIMER: Susceptibility scores reflect terrain, topographic, and edaphic susceptibility "
    "to landslide initiation under mapped inventory conditions. They do NOT represent real-time "
    "road closure probabilities, traffic disruption risks, or weather-induced hazard states."
)


def categorize_susceptibility(probability: float) -> str:
    """Categorize a probability score into LOW, MEDIUM, or HIGH susceptibility."""
    if np.isnan(probability):
        return "UNKNOWN"
    if probability < LOW_THRESHOLD:
        return "LOW"
    elif probability < HIGH_THRESHOLD:
        return "MEDIUM"
    else:
        return "HIGH"


def load_model(model_path: Optional[Union[str, Path]] = None) -> Any:
    """
    Load a trained model pipeline from joblib file.
    Falls back to baseline model if candidate/final v2 is not yet present.
    """
    if model_path is not None:
        path = Path(model_path)
    else:
        if DEFAULT_MODEL_PATH.exists():
            path = DEFAULT_MODEL_PATH
        elif FALLBACK_BASELINE_MODEL_PATH.exists():
            logger.warning(
                f"Model '{DEFAULT_MODEL_PATH}' not found; falling back to baseline '{FALLBACK_BASELINE_MODEL_PATH}'."
            )
            path = FALLBACK_BASELINE_MODEL_PATH
        else:
            raise FileNotFoundError(
                f"Neither '{DEFAULT_MODEL_PATH}' nor '{FALLBACK_BASELINE_MODEL_PATH}' exists."
            )

    if not path.exists():
        raise FileNotFoundError(f"Specified model path does not exist: {path}")

    logger.info(f"Loading model pipeline from: {path}")
    model = joblib.load(path)
    return model


def validate_input_data(
    df: pd.DataFrame,
    strict: bool = False
) -> Tuple[pd.DataFrame, List[str], List[str]]:
    """
    Validate input DataFrame against the expected feature schema.

    Returns:
        Tuple of (validated_feature_df, missing_features, extra_columns)
    """
    # Check for road scenario inputs lacking environmental features
    if "environmental_features_status" in df.columns:
        status_vals = df["environmental_features_status"].dropna().unique().tolist()
        if any("NOT_EXTRACTED" in str(v).upper() for v in status_vals):
            raise ValueError(
                "Input dataset contains road scenario records where environmental features "
                "have not been extracted from segment geometry ('NOT_EXTRACTED_FROM_SEGMENT_GEOMETRY'). "
                "Landslide susceptibility cannot be evaluated on unextracted road segments. "
                "Extract DEM, topographic, and SoilGrids raster features before running inference."
            )

    missing_features = [col for col in ALL_EXPECTED_FEATURES if col not in df.columns]
    extra_columns = [col for col in df.columns if col not in ALL_EXPECTED_FEATURES]

    if missing_features:
        msg = f"Input is missing {len(missing_features)} expected features: {missing_features}"
        if strict:
            raise ValueError(msg)
        else:
            logger.warning(msg)
            # Create missing columns with NaN to allow pipeline imputer to handle if configured
            feature_df = df.reindex(columns=ALL_EXPECTED_FEATURES).copy()
    else:
        feature_df = df[ALL_EXPECTED_FEATURES].copy()

    # Ensure numeric types
    for col in EXPECTED_NUMERICAL_FEATURES:
        if col in feature_df.columns:
            feature_df[col] = pd.to_numeric(feature_df[col], errors="coerce")

    return feature_df, missing_features, extra_columns


def predict_susceptibility(
    data: Union[pd.DataFrame, Dict[str, Any], List[Dict[str, Any]], str, Path],
    model: Optional[Any] = None,
    model_path: Optional[Union[str, Path]] = None,
    strict_validation: bool = False
) -> pd.DataFrame:
    """
    Execute landslide susceptibility predictions on input data.

    Parameters:
        data: Input DataFrame, dict, list of dicts, or CSV file path.
        model: Pre-loaded model pipeline (optional).
        model_path: Path to model pipeline if not pre-loaded (optional).
        strict_validation: If True, raises ValueError on missing features.

    Returns:
        DataFrame containing preserved IDs, predicted susceptibility score,
        categorical classification, and scientific disclaimer.
    """
    # 1. Ingest data
    if isinstance(data, (str, Path)):
        csv_path = Path(data)
        if not csv_path.exists():
            raise FileNotFoundError(f"Input file not found: {csv_path}")
        logger.info(f"Reading input CSV from: {csv_path}")
        input_df = pd.read_csv(csv_path)
    elif isinstance(data, dict):
        input_df = pd.DataFrame([data])
    elif isinstance(data, list):
        input_df = pd.DataFrame(data)
    elif isinstance(data, pd.DataFrame):
        input_df = data.copy()
    else:
        raise TypeError(f"Unsupported data type: {type(data)}")

    if len(input_df) == 0:
        raise ValueError("Input dataset is empty.")

    # 2. Identify and preserve identifiers
    preserved_id_cols = [c for c in ID_COLUMNS if c in input_df.columns]
    if preserved_id_cols:
        results_df = input_df[preserved_id_cols].copy()
    else:
        results_df = pd.DataFrame({"index": input_df.index})

    # 3. Validate features
    feature_df, missing_features, extra_cols = validate_input_data(
        input_df, strict=strict_validation
    )

    # 4. Load model
    if model is None:
        model = load_model(model_path)

    # 5. Predict probabilities
    try:
        probabilities = model.predict_proba(feature_df)[:, 1]
    except Exception as e:
        logger.error(f"Error during model prediction: {e}")
        raise

    # 6. Format results
    results_df["susceptibility_score"] = np.round(probabilities, 4)
    results_df["susceptibility_category"] = [
        categorize_susceptibility(p) for p in probabilities
    ]
    results_df["prediction_status"] = "SUCCESS"
    if missing_features:
        results_df["missing_features_imputed_count"] = len(missing_features)

    # Attach metadata attribute to DataFrame
    results_df.attrs["disclaimer"] = DISCLAIMER_TEXT
    results_df.attrs["thresholds"] = {
        "LOW": f"< {LOW_THRESHOLD}",
        "MEDIUM": f"{LOW_THRESHOLD} - {HIGH_THRESHOLD}",
        "HIGH": f">= {HIGH_THRESHOLD}"
    }

    logger.info(
        f"Inference completed successfully for {len(results_df)} records. "
        f"Distribution: {results_df['susceptibility_category'].value_counts().to_dict()}"
    )
    return results_df


def main():
    """Command-line interface for batch prediction."""
    parser = argparse.ArgumentParser(
        description="Landslide Susceptibility Model Batch Inference Script (Sikkim Pilot)"
    )
    parser.add_argument(
        "--input", "-i",
        required=True,
        type=str,
        help="Path to input CSV file containing candidate features."
    )
    parser.add_argument(
        "--output", "-o",
        required=True,
        type=str,
        help="Path where prediction results CSV will be saved."
    )
    parser.add_argument(
        "--model", "-m",
        default=None,
        type=str,
        help="Path to trained model pipeline (.joblib). Defaults to random_forest_final_v2.joblib."
    )
    parser.add_argument(
        "--strict",
        action="store_true",
        help="Enforce strict schema check (fail on any missing features)."
    )

    args = parser.parse_args()

    try:
        results = predict_susceptibility(
            data=args.input,
            model_path=args.model,
            strict_validation=args.strict
        )
        out_path = Path(args.output)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        results.to_csv(out_path, index=False)
        logger.info(f"Results successfully saved to: {out_path}")
        print("\n" + "=" * 70)
        print("LANDSLIDE SUSCEPTIBILITY PREDICTION COMPLETED")
        print("=" * 70)
        print(f"Output saved: {out_path}")
        print(f"Total records: {len(results)}")
        print("Category distribution:")
        for cat, cnt in results["susceptibility_category"].value_counts().items():
            print(f"  - {cat}: {cnt} ({cnt / len(results) * 100:.1f}%)")
        print("\n" + DISCLAIMER_TEXT)
        print("=" * 70 + "\n")
    except Exception as e:
        logger.error(f"Inference failed: {e}", exc_info=True)
        sys.exit(1)


if __name__ == "__main__":
    main()

